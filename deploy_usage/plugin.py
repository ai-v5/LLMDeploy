"""vLLM stat logger: same deltas as Prometheus, persisted on the host."""
import atexit
import os
import queue
import sys
import threading
import time

from vllm.v1.metrics.loggers import AggregateStatLoggerBase

from .store import Store


class UsageLogger(AggregateStatLoggerBase):
    def __init__(self, vllm_config, engine_indexes):
        self.failed = False
        self.store = None
        self.pending = queue.Queue(maxsize=4096)
        self.writer = threading.Thread(target=self._write, name='llmdeploy-usage', daemon=True)
        self.writer.start()
        atexit.register(self._close)

    def _fail(self):
        if not self.failed:
            self.failed = True
            print('LLMDEPLOY_USAGE_STORAGE_FAILED', file=sys.stderr)

    def _submit(self, item):
        if self.failed:
            return
        try:
            self.pending.put_nowait(item)
        except queue.Full:
            self._fail()

    def _write(self):
        try:
            self.store = Store(os.environ['LLMDEPLOY_USAGE_DIR'],
                os.environ['LLMDEPLOY_USAGE_RUN'], int(os.environ['LLMDEPLOY_USAGE_WRITERS']))
            marked = False
            while True:
                try:
                    item = self.pending.get(timeout=5)
                except queue.Empty:
                    item = ('heartbeat', time.time())
                if self.failed and not marked:
                    self.store.fail()
                    marked = True
                if item[0] == 'stop':
                    self.store.close()
                    return
                if item[0] == 'barrier':
                    item[1].set()
                elif item[0] == 'record':
                    self.store.record(item[1], item[2])
                elif not self.failed:
                    self.store.heartbeat(item[1])
        except Exception:
            self._fail()
            try:
                if self.store is not None:
                    self.store.fail()
            except Exception:
                pass
        finally:
            if self.store is not None:
                self.store.db.close()

    def record(self, scheduler_stats, iteration_stats, mm_cache_stats=None, engine_idx=0):
        if self.failed or iteration_stats is None:
            return
        try:
            self._record(iteration_stats)
        except Exception:
            self._fail()

    def _record(self, iteration_stats):
        stats = iteration_stats
        finished = stats.finished_requests
        values = (stats.num_prompt_tokens, stats.num_generation_tokens,
            stats.prompt_token_stats.cached_tokens, len(finished),
            sum(max(0, r.num_generation_tokens - 1) for r in finished),
            sum(max(0, r.decode_time) for r in finished))
        if any(values):
            self._submit(('record', values, stats.iteration_timestamp))

    def log(self):
        # Heartbeats are generated by the writer; no disk operation in callbacks.
        pass

    def log_engine_initialized(self):
        self.log()

    def _close(self):
        if self.writer.is_alive():
            try:
                self.pending.put(('stop',), timeout=0.1)
            except queue.Full:
                self._fail()
            self.writer.join(timeout=2)

    def flush(self, timeout=5):
        """Bounded barrier for offline validation; never used by inference."""
        barrier = threading.Event()
        self._submit(('barrier', barrier))
        return barrier.wait(timeout)
